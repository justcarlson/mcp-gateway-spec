"""Write, read, and check the frozen conformance profiles in conformance/.

A profile lists the rule IDs and levels that apply to one MCP revision, as
frozen by one spec release. After that release is tagged, the file never
changes (scripts/check_frozen.py enforces this in CI).

    python3 scripts/conformance.py --write 2026-07-28   # create a new profile
    python3 scripts/conformance.py --check              # profiles for this version match the registry

Stdlib only. The YAML is a fixed subset, so a strict line parser reads it.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from mcp_gateway_check import SPEC_VERSION  # noqa: E402
from mcp_gateway_check.revisions import load  # noqa: E402
from mcp_gateway_check.rules import RULES  # noqa: E402

DIR = ROOT / "conformance"
LEVELS = ("MUST", "MUST NOT", "SHOULD", "SHOULD NOT", "MAY")
_SCALAR = re.compile(r"^(spec_version|mcp_revision|frozen_in|upstream_tag|upstream_commit): (\S+)$")
_RULE = re.compile(r"^  - \{id: ([A-Z]+-\d+), level: (MUST NOT|MUST|SHOULD NOT|SHOULD|MAY)\}$")


@dataclass
class Profile:
    spec_version: str
    mcp_revision: str
    frozen_in: str
    upstream_tag: str
    upstream_commit: str
    rules: list[tuple[str, str]]


def path_for(revision: str) -> Path:
    return DIR / f"mcp-{revision}.yaml"


def render(revision: str) -> str:
    entry = load().revisions[revision]
    rules = [r for r in RULES.values() if r.applies_to(revision)]
    lines = [
        f"# FROZEN. Conformance profile for MCP {revision}, frozen by spec v{SPEC_VERSION}.",
        f"# Do not edit after the v{SPEC_VERSION} tag; CI fails if this file changes.",
        "# Later spec versions may add rules for this revision; they do not change this file.",
        "# Generated by scripts/conformance.py from the checker's rule registry.",
        f"spec_version: {SPEC_VERSION}",
        f"mcp_revision: {revision}",
        f"frozen_in: v{SPEC_VERSION}",
        f"upstream_tag: {entry['tag']}",
        f"upstream_commit: {entry['commit']}",
        f"rule_count: {len(rules)}",
        "rules:",
    ]
    lines += [f"  - {{id: {r.id}, level: {r.level}}}" for r in rules]
    return "\n".join(lines) + "\n"


def parse(text: str) -> Profile:
    """Strict reader for the subset render() writes. Raises ValueError on anything else."""
    lines = text.splitlines()
    if not lines or not lines[0].startswith("# FROZEN."):
        raise ValueError("first line must start with '# FROZEN.'")
    scalars: dict[str, str] = {}
    rules: list[tuple[str, str]] = []
    count = None
    in_rules = False
    for n, line in enumerate(lines, 1):
        if line.startswith("#"):
            continue
        if in_rules:
            m = _RULE.match(line)
            if not m:
                raise ValueError(f"line {n}: expected '  - {{id: X-1, level: MUST}}'")
            rules.append((m.group(1), m.group(2)))
        elif line == "rules:":
            in_rules = True
        elif m := _SCALAR.match(line):
            scalars[m.group(1)] = m.group(2)
        elif m := re.match(r"^rule_count: (\d+)$", line):
            count = int(m.group(1))
        else:
            raise ValueError(f"line {n}: unexpected {line!r}")
    missing = {"spec_version", "mcp_revision", "frozen_in", "upstream_tag", "upstream_commit"} - scalars.keys()
    if missing:
        raise ValueError(f"missing keys: {', '.join(sorted(missing))}")
    if count != len(rules):
        raise ValueError(f"rule_count {count} does not match {len(rules)} rules")
    if len({r for r, _ in rules}) != len(rules):
        raise ValueError("duplicate rule ID")
    return Profile(rules=rules, **scalars)


def check() -> list[str]:
    """Problems with the profiles in conformance/. Empty when all is well."""
    problems = []
    upstream = load()
    for revision in upstream.supported:
        if not path_for(revision).is_file():
            problems.append(f"{path_for(revision).name}: missing; run scripts/conformance.py --write {revision}")
    for path in sorted(DIR.glob("mcp-*.yaml")):
        try:
            profile = parse(path.read_text(encoding="utf-8"))
        except ValueError as exc:
            problems.append(f"{path.name}: {exc}")
            continue
        if path.name != f"mcp-{profile.mcp_revision}.yaml":
            problems.append(f"{path.name}: mcp_revision {profile.mcp_revision} does not match the file name")
        if profile.frozen_in == f"v{SPEC_VERSION}" and path.read_text(encoding="utf-8") != render(profile.mcp_revision):
            problems.append(f"{path.name}: differs from the registry; run scripts/conformance.py --write")
        for rule_id, _ in profile.rules:
            if rule_id not in RULES:
                problems.append(f"{path.name}: {rule_id} is not in the registry (IDs are never removed)")
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", metavar="REV", help="write conformance/mcp-REV.yaml for this spec version")
    ap.add_argument("--check", action="store_true", help="verify every profile")
    args = ap.parse_args(argv)
    if args.write:
        revision = load().resolve(args.write)
        if revision not in load().supported:
            ap.error("profiles are written for dated, supported revisions only")
        path_for(revision).write_text(render(revision), encoding="utf-8")
        print(f"wrote {path_for(revision).relative_to(ROOT)}")
        return 0
    problems = check()
    for p in problems:
        print(p, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
